const SKU_STORAGE_KEY = "erp_products_sku_catalog_v2";

export function getStoredSkus(): SkuProduct[] {
  try {
    const raw = localStorage.getItem(SKU_STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(SKU_STORAGE_KEY, JSON.stringify(INITIAL_SKUS));
      return INITIAL_SKUS;
    }
    return JSON.parse(raw);
  } catch {
    return INITIAL_SKUS;
  }
}

export function saveStoredSkus(skus: SkuProduct[]): void {
  try {
    localStorage.setItem(SKU_STORAGE_KEY, JSON.stringify(skus));
  } catch (err) {
    console.error("Failed to save SKUs", err);
  }
}

export function getStoredSkuProducts(): SkuProduct[] {
  return getStoredSkus();
}

export function saveStoredSkuProducts(skus: SkuProduct[]): void {
  saveStoredSkus(skus);
}

export function daysBetween(dateStr: string): number {
  if (!dateStr) return 0;
  const d = new Date(dateStr).getTime();
  const now = new Date("2026-11-22").getTime();
  const diffDays = Math.floor((now - d) / (1000 * 3600 * 24));
  return Math.max(0, diffDays);
}
